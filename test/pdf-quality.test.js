const test = require("node:test");
const assert = require("node:assert");
const { mangleScore, isMangled } = require("../src/pdf-quality.js");

// نص عربي سليم مخترع، بطول كافٍ للحكم
const GOOD = `في يوم الخميس الموافق الخامس والعشرين من شهر ربيع الآخر لعام ألف وأربعمائة وخمسة
وأربعين افتتحت الجلسة عن طريق برنامج التواصل المرئي عن بعد وحضرت المدعية وكالة وقدمت
دعواها مكتوبة وذكرت فيها أن موكلها اتفق مع المؤسسة على شراء مركبة من الشركة البائعة
بمبلغ وقدره مئة وثمانية وخمسون ألف ريال على أقساط شهرية متساوية وأنه سدد الأقساط كاملة
ثم طلبت الحكم بنقل ملكية المركبة إليه وإلزام المدعى عليها بالرسوم والمصاريف هكذا قررت`;

// النص نفسه بعد استخراج مقلوب: كلمات مقطّعة وأرقام ملتصقة
const MANGLED = `هـ الساعة /1445 /4 25في يوم الخميس ة الحاضر بصفة تيمز بعد عن المرئي التواصل برنامج
ب ش ر ى ع ب د ا ل ر ح ي م سعودية الجنسية بموجب السجل رقم 1088423122وكيلة عن نواف
م باالتفاق مع مؤسسة /2012 /7 31قام موكلي في تاريخ لوحة 5219رقم ب ن م 2012كس أر موديل
ا ه ع ن م ي ر ا ت وذلك بأقساط وقدرها 4402أربعة األف وأربعمائة ل ا ي ر`;

test("النص العربي السليم لا يُعدّ مبعثرًا", () => {
  assert.ok(mangleScore(GOOD) < 0.25, `النتيجة ${mangleScore(GOOD)}`);
  assert.equal(isMangled(GOOD), false);
});

test("النص المبعثر يُكتشف", () => {
  assert.ok(mangleScore(MANGLED) > 0.25, `النتيجة ${mangleScore(MANGLED)}`);
  assert.equal(isMangled(MANGLED), true);
});

test("الكلمات المقطّعة حرفًا حرفًا تُكتشف", () => {
  const t = Array(60).fill("ا ل م د ع ي").join(" ");
  assert.equal(isMangled(t), true);
});

test("التصاق الأرقام بالحروف: قليله يُحتمل وكثيره يُكتشف", () => {
  const base = Array(60).fill("المدعي").join(" ");
  // خمس مواضع في خمسة وستين كلمة قد تقع في نص سليم، فلا تُرفع راية
  assert.equal(isMangled(`${base} 1445في 850000ريال 2012كس 5219لوحة 899عبدالرحيم`), false);
  // أما ربع الكلمات فهو انقلاب ترتيب لا صدفة
  const glued = Array(20).fill("1445في 850000ريال").join(" ");
  assert.equal(isMangled(`${base} ${glued}`), true);
});

test("النص القصير لا يُحكم عليه", () => {
  assert.equal(mangleScore("ا ل م د ع ي ب ش ر ى"), 0, "عيّنة أصغر من أن تدل");
  assert.equal(isMangled(""), false);
  assert.equal(isMangled(null), false);
});

test("الأرقام المفصولة عن الكلمات لا تُعدّ عيبًا", () => {
  const t = `${Array(60).fill("المدعي يطلب").join(" ")} بمبلغ 850000 ريال بتاريخ 1445 هـ`;
  assert.equal(isMangled(t), false);
});
