const test = require("node:test");
const assert = require("node:assert");
const { maskNames, maskNumbers, leftovers } = require("../tools/midad-analyze.js");

const N = ["بشرى عبدالرحيم زائد القرشي", "صقر عبيد بن عبدالرحمن المطيري", "نواف سعران بن بنيدر الحميداني"];

test("يبقي أول اسمين ويستر الباقي", () => {
  assert.equal(maskNames("الحاضرة بشرى عبدالرحيم زائد القرشي سعودية", N), "الحاضرة بشرى عبدالرحيم **** سعودية");
});

test("يتجاوز «بن» بين الأجزاء", () => {
  assert.equal(maskNames("الشاهد صقر عبيد بن عبدالرحمن المطيري حضر", N), "الشاهد صقر عبيد **** حضر");
});

test("يمسك الاسم وقد قطعه سطر بين جزأيه", () => {
  const t = "الحاضرة بشرى\nعبدالرحيم زائد القرشي سعودية";
  assert.ok(!leftovers(maskNames(t, N), N).length, maskNames(t, N));
});

test("يمسك اللقب وقد قُطع بسطر داخل الكلمة", () => {
  const t = "صقر عبيد بن عبدالرحمن\nالمط\nيرى سعودي";
  const out = maskNames(t, N);
  assert.ok(!/المط/.test(out), out);
  assert.ok(!/عبدالرحمن/.test(out), out);
});

test("يقبل اختلاف شكل الحرف (ى/ي و ة/ه و أ/ا)", () => {
  assert.ok(!leftovers(maskNames("نواف سعران بن بنيدر الحميدانى", N), N).length);
});

test("لا يمسّ اسمًا أول لطرف آخر مذكور في القائمة", () => {
  // «فهد» جزء مستور في الاسم الأول، وهو أول اسم للطرف الثاني: فيبقى ظاهرًا بحقّه
  const names = ["أحمد بجاد فهد المطيري", "فهد بجاد فهد العضيله"];
  const out = maskNames("المدعى عليه أحمد بجاد فهد المطيري ووكيله فهد بجاد", names);
  assert.ok(out.includes("أحمد بجاد ****"), out);
  assert.ok(out.includes("ووكيله فهد بجاد"), out);
});

test("يكنس الجزء المستور ولو تفرّق عن أول الاسم", () => {
  // الاستخراج المعكوس يفصل «بشرى» عن بقية اسمها، فلا تكفي مطابقة الاسم كاملًا
  const out = maskNames("رقم 899 عبدالرحيم زائد القرشي سعودية", N);
  assert.ok(!/زائد|القرشي/.test(out), out);
});

test("طرفٌ لم يُذكر في القائمة قد يُستر اسمه الأول احتياطًا", () => {
  // اتجاه الخطأ الآمن: ستْرٌ زائد لا كشف. والتقرير يبيّن ما استُتر.
  const out = maskNames("ووكيله فهد بجاد", ["أحمد بجاد فهد المطيري"]);
  assert.ok(!out.includes("فهد بجاد"), out);
});

test("لا يبتلع نجوم الأرقام عند جمع علامات الأسماء", () => {
  const t = maskNumbers("السجل رقم 1088423122", 8, 3);
  assert.equal(t, "السجل رقم *******122");
  assert.equal(maskNames(t, N), "السجل رقم *******122");
});

test("leftovers يبلّغ عن جزء أفلت من الحجب", () => {
  assert.deepEqual(leftovers("بشرى عبدالرحيم زائد ****", N), ["زائد"]);
  assert.deepEqual(leftovers("بشرى عبدالرحيم ****", N), []);
});

test("يستر شظية اللقب إذا وقفت كلمة وحدها", () => {
  const names = ["صقر عبيد بن عبدالرحمن المطيري"];
  const out = maskNames("بموجب السجل رقم المط\nولكني حضرت", names);
  assert.ok(!/المط/.test(out), out);
});

test("لا يمسّ كلمة عربية تبدأ بحروف اللقب", () => {
  const names = ["صقر عبيد بن عبدالرحمن المطيري"];
  const out = maskNames("لا تتناسب مع المبلغ المطالب به في المطالبة", names);
  assert.equal(out, "لا تتناسب مع المبلغ المطالب به في المطالبة");
});
