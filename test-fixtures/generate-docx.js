"use strict";
const fs = require("fs");
const path = require("path");
const { Document, Packer, Paragraph, TextRun, AlignmentType, PageBreak, HeadingLevel } = require("docx");

const OUT = __dirname;

const P = (text, o = {}) => new Paragraph({
  bidirectional: true,
  alignment: o.center ? AlignmentType.CENTER : AlignmentType.RIGHT,
  spacing: { after: o.after == null ? 140 : o.after, line: 340 },
  children: [new TextRun({ text, rightToLeft: true, bold: !!o.bold, size: o.size || 24, font: "Arial" })],
});
const BREAK = () => new Paragraph({ children: [new PageBreak()] });

async function write(name, paragraphs) {
  const doc = new Document({ sections: [{ properties: {}, children: paragraphs }] });
  const buf = await Packer.toBuffer(doc);
  fs.writeFileSync(path.join(OUT, name), buf);
  console.log("كُتب:", name, `(${Math.round(buf.length / 1024)} ك.ب)`);
}

